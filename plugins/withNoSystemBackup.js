/**
 * Android system backup and device transfer OFF for Xayra (Gate 2, approved
 * Option A).
 *
 * Why: Android's own Auto Backup used expo-secure-store's rules, which back
 * up every shared-preferences file except SecureStore — including
 * expo-notifications' store of scheduled reminders, i.e. to-do text in
 * plaintext, sent to the Google account's device backup and copied in
 * phone-to-phone transfers. The vault itself was already excluded (and is
 * unreadable without its Keystore-held key anyway).
 *
 * What this sets on <application>:
 *  - android:allowBackup="false" — no Auto Backup / key-value backup
 *    (Android 11 and lower: no backup or device transfer at all).
 *  - android:fullBackupContent → rules excluding every domain, in case a
 *    platform or tool still consults them.
 *  - android:dataExtractionRules → rules excluding every domain from BOTH
 *    cloud backup and device-to-device transfer. Needed because on
 *    Android 12+ (targetSdk 31+), allowBackup="false" does not stop
 *    device-to-device transfer by itself.
 *
 * Unaffected: in-place app updates (Play or adb) keep app-private data — they
 * are not backups. Xayra's own encrypted Google Drive backup is separate code
 * and is unchanged. Changing phones: notes come back through Xayra's own
 * encrypted backup / "Recover my notes", never through Android's transfer.
 * Backups Android already made of earlier versions stay in the Google account
 * until Google expires them; with allowBackup="false" Android won't restore
 * them into this app.
 *
 * Registered AFTER expo-secure-store in app.json, whose own backup rules are
 * switched off there (configureAndroidBackup: false).
 */
const fs = require("fs");
const path = require("path");
const { withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

const BACKUP_RULES = "xayra_backup_rules";
const EXTRACTION_RULES = "xayra_data_extraction_rules";

// Every domain Android's backup rules know, credential- and device-protected.
const DOMAINS = [
  "root",
  "file",
  "database",
  "sharedpref",
  "external",
  "device_root",
  "device_file",
  "device_database",
  "device_sharedpref",
];
const excludeAll = (indent) => DOMAINS.map((d) => `${indent}<exclude domain="${d}" path="." />`).join("\n");

const backupRulesXml = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNoSystemBackup.js — do not edit. Android 11 and lower: nothing is backed up. -->
<full-backup-content>
${excludeAll("  ")}
</full-backup-content>
`;

const extractionRulesXml = () => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNoSystemBackup.js — do not edit. Android 12+: nothing leaves the phone through cloud backup or device transfer. -->
<data-extraction-rules>
  <cloud-backup>
${excludeAll("    ")}
  </cloud-backup>
  <device-transfer>
${excludeAll("    ")}
  </device-transfer>
</data-extraction-rules>
`;

function withNoSystemBackup(config) {
  config = withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (!app) throw new Error("withNoSystemBackup: no <application> in AndroidManifest.xml");
    app.$["android:allowBackup"] = "false";
    app.$["android:fullBackupContent"] = `@xml/${BACKUP_RULES}`;
    app.$["android:dataExtractionRules"] = `@xml/${EXTRACTION_RULES}`;
    return cfg;
  });
  config = withDangerousMod(config, [
    "android",
    async (cfg) => {
      const xmlDir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res", "xml");
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${BACKUP_RULES}.xml`), backupRulesXml());
      fs.writeFileSync(path.join(xmlDir, `${EXTRACTION_RULES}.xml`), extractionRulesXml());
      return cfg;
    },
  ]);
  return config;
}

module.exports = withNoSystemBackup;
module.exports.DOMAINS = DOMAINS;
module.exports.backupRulesXml = backupRulesXml;
module.exports.extractionRulesXml = extractionRulesXml;

/**
 * Android launcher shortcuts: long-press the Xayra icon (or pin to the home
 * screen) for "Record with Xayra" / "Ask Xayra". Each opens the app with
 * `<scheme>://shortcut?mode=record|ask`; app/+native-intent.tsx and Home
 * take it from there (services/shortcuts/launchShortcut.ts).
 *
 * Static shortcuts (res/xml/shortcuts.xml) — no dependency, no runtime
 * code. Package and scheme come from the resolved config, so production
 * (com.anonymous.silentconfidant / xayra) and Xayra Dev
 * (com.anonymous.silentconfidant.dev / xayra-dev) each target only
 * themselves.
 *
 * TRAMPOLINE: Android always adds NEW_TASK|CLEAR_TASK to a static
 * shortcut's intent. Aimed straight at MainActivity, that destroyed and
 * re-created the running activity on every warm launch (confirmed in the
 * wm_* event log): no onNewIntent, a full React remount that wiped Home's
 * state (mode, busy recording), and an initial-URL read that returned the
 * OUTGOING activity's intent — i.e. the previous launch's shortcut. So the
 * shortcut targets ShortcutLaunchActivity instead: invisible, in its own
 * task (so CLEAR_TASK only clears that), it forwards the link to the
 * singleTop MainActivity (CLEAR_TOP | SINGLE_TOP) and finishes. Warm: MainActivity gets onNewIntent
 * (a normal deep-link "url" event, no remount). Cold: MainActivity starts
 * with the link as its own initial intent.
 *
 * Also guards MainActivity: if Android restores the activity from Recents
 * after the process died, it replays the ORIGINAL launch intent — which
 * would be the shortcut, starting a recording nobody asked for. A shortcut
 * intent launched from history is dropped before React Native reads it.
 */

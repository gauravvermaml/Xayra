const TRAMPOLINE = "ShortcutLaunchActivity";
const BACKGROUND = "#0E0F12"; // app.json adaptive-icon background
const GLYPH = "#FFFFFF";
const MARKER = "xayra-app-shortcuts";

function shortcutUri(scheme, mode) {
  return `${scheme}://shortcut?mode=${mode}`;
}

function buildShortcutsXml({ packageName, scheme }) {
  const items = SHORTCUTS.map(
    (s) => `  <shortcut
    android:shortcutId="${s.id}"
    android:enabled="true"
    android:icon="@drawable/${s.icon}"
    android:shortcutShortLabel="@string/shortcut_${s.id}_short"
    android:shortcutLongLabel="@string/shortcut_${s.id}_long">
    <intent
      android:action="android.intent.action.VIEW"
      android:targetPackage="${packageName}"
      android:targetClass="${packageName}.${TRAMPOLINE}"
      android:data="${shortcutUri(scheme, s.mode)}" />
  </shortcut>`
  ).join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAppShortcuts.js — do not edit. -->
<shortcuts xmlns:android="http://schemas.android.com/apk/res/android">
${items}
</shortcuts>
`;
}

function buildIconXml(glyph) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAppShortcuts.js — do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
  android:width="48dp"
  android:height="48dp"
  android:viewportWidth="48"
  android:viewportHeight="48">
  <path android:fillColor="${BACKGROUND}" android:pathData="M24,0A24,24 0,1 1,24,48A24,24 0,1 1,24,0Z" />
  <group android:translateX="12" android:translateY="12">
    <path android:fillColor="${GLYPH}" android:pathData="${glyph}" />
  </group>
</vector>
`;
}

const ACTIVITY_GUARD = `    // @generated begin ${MARKER}
    // Restored from Recents after the process died: Android replays the
    // original launch intent. Drop a launcher-shortcut one so reopening
    // Xayra never starts recording by itself.
    if ((intent.flags and android.content.Intent.FLAG_ACTIVITY_LAUNCHED_FROM_HISTORY) != 0 &&
        intent.data?.host == "shortcut") {
      intent.data = null
    }
    // @generated end ${MARKER}
`;

function buildTrampolineKotlin(packageName) {
  return `// Generated by plugins/withAppShortcuts.js — do not edit.
package ${packageName}

import android.app.Activity
import android.content.Intent
import android.os.Bundle

/**
 * Receives a launcher shortcut in its own task (absorbing the NEW_TASK |
 * CLEAR_TASK Android adds to shortcut intents) and forwards the link to the
 * singleTop MainActivity: onNewIntent when Xayra is running (CLEAR_TOP |
 * SINGLE_TOP reuse the running instance, as singleTask did), a normal
 * launch when it isn't. Only shortcut links are forwarded.
 */
class ${TRAMPOLINE} : Activity() {
  override fun onCreate(savedInstanceState: Bundle?) {
    super.onCreate(savedInstanceState)
    val data = intent?.data
    val forward = Intent(this, MainActivity::class.java).addFlags(
      Intent.FLAG_ACTIVITY_NEW_TASK or Intent.FLAG_ACTIVITY_CLEAR_TOP or Intent.FLAG_ACTIVITY_SINGLE_TOP
    )
    if (data != null && data.host == "shortcut") {
      forward.action = Intent.ACTION_VIEW
      forward.data = data
    }
    startActivity(forward)
    finish()
    overridePendingTransition(0, 0)
  }
}
`;
}

function addActivityGuard(source) {
  if (source.includes(`@generated begin ${MARKER}`)) return source;
  const anchor = /^(\s*)super\.onCreate\(/m;
  if (!anchor.test(source)) {
    throw new Error(`[${MARKER}] Couldn't find super.onCreate( in MainActivity to add the Recents guard.`);
  }
  return source.replace(anchor, (match) => `${ACTIVITY_GUARD}${match}`);
}

function withAppShortcuts(config) {
  const packageName = config.android && config.android.package;
  const scheme = Array.isArray(config.scheme) ? config.scheme[0] : config.scheme;
  if (!packageName || !scheme) {
    throw new Error(`[${MARKER}] Needs android.package and scheme in the app config.`);
  }

  config = withStringsXml(config, (cfg) => {
    for (const s of SHORTCUTS) {
      for (const [suffix, value] of [
        ["short", s.shortLabel],
        ["long", s.longLabel],
      ]) {
        cfg.modResults = AndroidConfig.Strings.setStringItem(
          [AndroidConfig.Resources.buildResourceItem({ name: `shortcut_${s.id}_${suffix}`, value })],
          cfg.modResults
        );
      }
    }
    return cfg;
  });

  config = withAndroidManifest(config, (cfg) => {
    const activity = AndroidConfig.Manifest.getMainActivityOrThrow(cfg.modResults);
    // singleTop, not Expo's default singleTask: returning to Xayra from the
    // launcher icon while Google Play's purchase screen is open (e.g. after
    // checking a bank app) must not clear that screen and cancel the purchase
    // (RevenueCat's Android guidance). Shortcuts keep reusing the running
    // activity through the trampoline's CLEAR_TOP | SINGLE_TOP.
    activity.$["android:launchMode"] = "singleTop";
    const metaData = (activity["meta-data"] = activity["meta-data"] || []);
    if (!metaData.some((m) => m.$["android:name"] === "android.app.shortcuts")) {
      metaData.push({ $: { "android:name": "android.app.shortcuts", "android:resource": "@xml/shortcuts" } });
    }
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(cfg.modResults);
    // Always (re)written, never trusted from an existing manifest — a
    // previously generated android/ folder may belong to the other variant.
    app.activity = (app.activity || []).filter((a) => a.$["android:name"] !== `.${TRAMPOLINE}`);
    app.activity.push({
      $: {
        "android:name": `.${TRAMPOLINE}`,
        // Exported like MainActivity's own VIEW filter (and only forwards
        // shortcut links), so it adds no new entry point.
        "android:exported": "true",
        "android:taskAffinity": `${packageName}.shortcut`,
        "android:excludeFromRecents": "true",
        "android:noHistory": "true",
        "android:theme": "@android:style/Theme.NoDisplay",
      },
    });
    return cfg;
  });

  config = withDangerousMod(config, [
    "android",
    (cfg) => {
      const res = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "res");
      fs.mkdirSync(path.join(res, "xml"), { recursive: true });
      fs.mkdirSync(path.join(res, "drawable"), { recursive: true });
      fs.writeFileSync(path.join(res, "xml", "shortcuts.xml"), buildShortcutsXml({ packageName, scheme }));
      for (const s of SHORTCUTS) {
        fs.writeFileSync(path.join(res, "drawable", `${s.icon}.xml`), buildIconXml(s.glyph));
      }
      const javaDir = path.join(cfg.modRequest.platformProjectRoot, "app", "src", "main", "java", ...packageName.split("."));
      fs.mkdirSync(javaDir, { recursive: true });
      fs.writeFileSync(path.join(javaDir, `${TRAMPOLINE}.kt`), buildTrampolineKotlin(packageName));
      return cfg;
    },
  ]);

  config = withMainActivity(config, (cfg) => {
    if (cfg.modResults.language !== "kt") {
      throw new Error(`[${MARKER}] Expected a Kotlin MainActivity.`);
    }
    cfg.modResults.contents = addActivityGuard(cfg.modResults.contents);
    return cfg;
  });

  return config;
}


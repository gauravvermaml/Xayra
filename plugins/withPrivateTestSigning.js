const { withAppBuildGradle } = require("expo/config-plugins");

/**
 * Signs the emulator-only "Xayra Test" variant (APP_VARIANT=devtest,
 * com.anonymous.silentconfidant.devtest) with a PRIVATE keystore instead of
 * the stock Expo/React Native debug keystore, whose private key is public.
 * Its Android OAuth client can then be registered without letting anyone
 * else impersonate the app.
 *
 * - Applied only by app.config.js's devtest branch; production and Xayra Dev
 *   never load it, and it refuses any package that isn't the devtest one.
 * - Credentials come from Gradle properties defined OUTSIDE the repository
 *   (the user-level ~/.gradle/gradle.properties):
 *     XAYRA_TEST_STORE_FILE, XAYRA_TEST_STORE_PASSWORD,
 *     XAYRA_TEST_KEY_ALIAS, XAYRA_TEST_KEY_PASSWORD
 *   Nothing secret is written into android/ or this repo.
 * - If any is missing the build fails — it never falls back to the public key.
 * - Re-applied on every prebuild, so it survives `expo prebuild --clean`.
 */
const MARKER = "// xayra-private-test-signing";
const TEST_PACKAGE = "com.anonymous.silentconfidant.devtest";

const GRADLE_BLOCK = `
${MARKER} (generated by plugins/withPrivateTestSigning.js — do not edit)
def xayraTestSigning = ["XAYRA_TEST_STORE_FILE", "XAYRA_TEST_STORE_PASSWORD", "XAYRA_TEST_KEY_ALIAS", "XAYRA_TEST_KEY_PASSWORD"].collectEntries { [(it): findProperty(it)] }
def xayraTestMissing = xayraTestSigning.findAll { it.value == null || it.value.toString().isEmpty() }.keySet()
if (!xayraTestMissing.isEmpty()) {
    throw new GradleException("Xayra Test private signing isn't configured (missing: " + xayraTestMissing.join(", ") + "). Define them in ~/.gradle/gradle.properties — see CLAUDE.md. Refusing to sign with the public debug key.")
}
android {
    signingConfigs {
        xayraTestPrivate {
            storeFile file(xayraTestSigning.XAYRA_TEST_STORE_FILE)
            storePassword xayraTestSigning.XAYRA_TEST_STORE_PASSWORD
            keyAlias xayraTestSigning.XAYRA_TEST_KEY_ALIAS
            keyPassword xayraTestSigning.XAYRA_TEST_KEY_PASSWORD
        }
    }
    buildTypes {
        debug { signingConfig signingConfigs.xayraTestPrivate }
        release { signingConfig signingConfigs.xayraTestPrivate }
    }
}
`;

module.exports = function withPrivateTestSigning(config) {
  const packageName = config.android && config.android.package;
  if (packageName !== TEST_PACKAGE) {
    throw new Error(`withPrivateTestSigning only applies to ${TEST_PACKAGE}, not ${packageName}.`);
  }
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== "groovy") {
      throw new Error("withPrivateTestSigning expects a Groovy app/build.gradle.");
    }
    if (!cfg.modResults.contents.includes(MARKER)) {
      cfg.modResults.contents = `${cfg.modResults.contents.trimEnd()}\n${GRADLE_BLOCK}`;
    }
    return cfg;
  });
};
